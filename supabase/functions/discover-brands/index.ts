const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};
function respond(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json', ...corsHeaders },
  });
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return respond({}, 200);
  try {
    const body = await req.json().catch(() => ({}));
    const exaKey = Deno.env.get('EXA_API_KEY');
    const anthropicKey = Deno.env.get('ANTHROPIC_API_KEY');
    if (!exaKey) {
      return respond({ error: 'EXA_API_KEY secret not configured' }, 500);
    }

    // Pull current brand state — all four queries in parallel. Approved and
    // rejected both now pull matched_categories/matched_styles/judge_reasoning
    // too, not just name/domain — that's the data buildTasteProfile() and
    // summarizeRejectionPatterns() turn into real steering signal below.
    const admin = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!);
    const [{ data: allBrands }, { data: rejectedBrands }, { data: approvedBrands }, { data: handPickedBrands }] = await Promise.all([
      admin.from('brands').select('domain'),
      admin.from('brands').select('name, judge_reasoning, rejection_note').eq('status', 'rejected').order('created_at', { ascending: false }).limit(100),
      admin.from('brands').select('name, domain, matched_categories, matched_styles').eq('status', 'approved').limit(500),
      admin.from('brands').select('name, domain').eq('status', 'approved').eq('hand_picked', true),
    ]);

    const knownDomains = new Set((allBrands ?? []).map(b => cleanDomain(b.domain)));
    const rejected = (rejectedBrands ?? []) as { name: string; judge_reasoning?: string | null; rejection_note?: string | null }[];
    const rejectedNames = rejected.map(b => b.name).filter(Boolean);
    const approved = (approvedBrands ?? []) as { name: string; domain: string; matched_categories?: string[] | null; matched_styles?: string[] | null }[];
    const handPicked = (handPickedBrands ?? []) as { name: string; domain: string }[];

    const tasteProfile = buildTasteProfile(approved);
    const rejectionPatterns = anthropicKey ? await summarizeRejectionPatterns(anthropicKey, rejected) : '';

    // { "custom_query": "..." } runs ONE ad-hoc themed Exa search — for
    // cheaply testing a hunch about a specific aesthetic ("New England
    // heritage prep") before deciding it's worth a permanent layer.
    // Short-circuits everything else, same isolation idea as
    // only_hand_picked, so a few exploratory pulls don't also pay for the
    // seed/editorial/keyword layers every time.
    if (typeof body.custom_query === 'string' && body.custom_query.trim()) {
      const found = await searchExaStorefronts(exaKey, body.custom_query.trim(), rejectedNames, rejectionPatterns);
      const candidates = found
        .map(b => ({ ...b, domain: cleanDomain(b.domain), source: 'custom' as const }))
        .filter(c => c.domain && !knownDomains.has(c.domain));
      return respond({ found_new: candidates.length, breakdown: { custom: candidates.length }, candidates });
    }

    // { "only_hand_picked": true } skips every layer except layer 0 — for
    // cheaply exploring what similarity search against just the hand-picked
    // list finds, without also paying for (and having to filter out) the
    // seed/editorial/keyword/nuuly layers' Exa + Anthropic calls.
    const onlyHandPicked = !!body.only_hand_picked;

    // Layers 0, 1, 2 run every time; Layer 4 (Nuuly) was a one-time bootstrap
    // source, not meant to carry ongoing weight — only runs when explicitly
    // requested via { "include_nuuly": true }, not on every regular call.
    const [handPickedCandidates, seedCandidates, editorialCandidates, nuulyCandidates] = await Promise.all([
      discoverFromHandPicked(exaKey, handPicked, rejectedNames, rejectionPatterns, knownDomains),
      onlyHandPicked
        ? Promise.resolve([] as Candidate[])
        : discoverFromSeeds(exaKey, approved, rejectedNames, rejectionPatterns, tasteProfile, knownDomains),
      !onlyHandPicked && anthropicKey
        ? discoverFromEditorial(exaKey, anthropicKey, knownDomains, rejectedNames, rejectionPatterns)
        : Promise.resolve([] as Candidate[]),
      !onlyHandPicked && anthropicKey && body.include_nuuly
        ? discoverFromNuuly(exaKey, anthropicKey, knownDomains, rejectedNames, rejectionPatterns)
        : Promise.resolve([] as Candidate[]),
    ]);

    // Layer 3: keyword fallback — exclude anything layers 0+1+2+4 already found
    const alreadyFound = new Set([
      ...knownDomains,
      ...handPickedCandidates.map(c => c.domain),
      ...seedCandidates.map(c => c.domain),
      ...editorialCandidates.map(c => c.domain),
      ...nuulyCandidates.map(c => c.domain),
    ]);
    const keywordCandidates = onlyHandPicked
      ? []
      : await discoverFromKeywords(exaKey, rejectedNames, rejectionPatterns, alreadyFound);

    // Final dedup — hand-picked candidates first (highest signal, so they win any domain collision)
    const seenDomains = new Set<string>();
    const candidates: Candidate[] = [];
    for (const c of [...handPickedCandidates, ...seedCandidates, ...editorialCandidates, ...nuulyCandidates, ...keywordCandidates]) {
      const domain = cleanDomain(c.domain);
      if (!domain || seenDomains.has(domain) || knownDomains.has(domain)) continue;
      seenDomains.add(domain);
      candidates.push({ ...c, domain });
    }

    return respond({
      found_new: candidates.length,
      breakdown: {
        hand_picked: handPickedCandidates.filter(c => !knownDomains.has(c.domain)).length,
        seed:        seedCandidates.filter(c => !knownDomains.has(c.domain)).length,
        editorial:   editorialCandidates.filter(c => !knownDomains.has(c.domain)).length,
        nuuly:       nuulyCandidates.filter(c => !knownDomains.has(c.domain)).length,
        keyword:     keywordCandidates.filter(c => !knownDomains.has(c.domain)).length,
      },
      context: {
        approved_seeds: approved.length,
        hand_picked_seeds: handPicked.length,
        rejected_anti_examples: rejectedNames.length,
        editorial_enabled: !!anthropicKey,
        taste_profile: tasteProfile || null,
        rejection_patterns: rejectionPatterns || null,
      },
      candidates,
    });
  } catch (err) {
    return respond({ error: String(err) }, 500);
  }
});


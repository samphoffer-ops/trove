// THREE-LAYER BRAND DISCOVERY
//
// Layer 1 — Seed-based: pull approved brands from the DB and use them as taste
// signals. Tells Exa "find me brands like these" — anchors on real curatorial
// decisions rather than abstract keyword guesses. Automatically improves as
// the catalog grows.
//
// Layer 2 — Editorial: search Highsnobiety, Monocle, GQ, Hypebeast, and similar
// publications for brand mentions in their "best of" / discovery content. These
// publications do curatorial work aligned with Trove's taste — surfacing brands
// they've featured is much stronger signal than keyword queries.
//
// Layer 3 — Keyword fallback: category-specific quality-first queries, focused
// on craft/heritage/premium positioning. Runs last so it fills gaps the first
// two layers miss, not as primary signal.
//
// Rejected brands from the DB are passed as anti-examples into every Exa prompt
// so the model learns from what Sam has already turned down.
//
// TASTE PROFILE — approved and rejected brands both carry matched_categories,
// matched_styles, and (for rejections) judge_reasoning, generated by the judge
// in catalog-intake and stored on every brand row. Previously none of that
// reached this function: positive signal was a random sample of ~16 approved
// brand *names*, and negative signal was the last 10-12 rejected brand names
// with no reasoning — so review decisions barely compounded into better
// discovery. buildTasteProfile() aggregates category/style frequency across
// the whole approved set (deterministic, no LLM). summarizeRejectionPatterns()
// distills recurring rejection reasoning into a handful of traits to avoid —
// one Claude call per run, not per brand or per query, reused everywhere.

const FETCH_TIMEOUT_MS = 12000;
function fetchWithTimeout(url: string, init: RequestInit = {}) {
  return fetch(url, { ...init, signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
}
function sleep(ms: number) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

interface Candidate {
  name: string;
  domain: string;
  source: 'hand_picked' | 'seed' | 'editorial' | 'keyword' | 'nuuly';
}

function cleanDomain(raw: string): string {
  return (raw ?? '').toLowerCase().trim()
    .replace(/^https?:\/\//, '')
    .replace(/^www\./, '')
    .replace(/\/.*$/, '');
}

// Deterministic frequency count across the WHOLE approved set — not a random
// sample, so it keeps reflecting the real catalog as it grows past what fits
// in a single prompt's brand-name list.
function buildTasteProfile(approved: { matched_categories?: string[] | null; matched_styles?: string[] | null }[]): string {
  const categoryCounts = new Map<string, number>();
  const styleCounts = new Map<string, number>();
  for (const b of approved) {
    for (const c of b.matched_categories ?? []) categoryCounts.set(c, (categoryCounts.get(c) ?? 0) + 1);
    for (const s of b.matched_styles ?? []) styleCounts.set(s, (styleCounts.get(s) ?? 0) + 1);
  }
  const top = (m: Map<string, number>, n: number) =>
    [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, n).map(([k]) => k);
  const categories = top(categoryCounts, 8);
  const styles = top(styleCounts, 10);
  if (categories.length === 0 && styles.length === 0) return '';
  return `The approved catalog skews toward these categories: ${categories.join(', ')}. Recurring style/aesthetic tags: ${styles.join(', ')}.`;
}

// One Claude call per discover-brands run (not per layer, not per brand) that
// distills actual judge_reasoning from rejected brands into recurring traits
// to avoid — turns "sounds like a name we rejected" into "has the qualities
// we've actually been rejecting for."
async function summarizeRejectionPatterns(
  anthropicKey: string,
  rejected: { name: string; judge_reasoning?: string | null; rejection_note?: string | null }[],
): Promise<string> {
  // rejection_note is Sam's own reason for a manual override and takes
  // priority — judge_reasoning on a brand that reached the review queue
  // argues FOR it (an approve verdict), so using it as rejection signal on
  // a brand Sam then rejected was actively backwards. Fall back to
  // judge_reasoning only for brands the AI itself auto-rejected, where it's
  // genuine anti-signal.
  const withReasoning = rejected
    .map(b => ({ name: b.name, reason: b.rejection_note || b.judge_reasoning }))
    .filter((b): b is { name: string; reason: string } => !!b.reason);
  if (withReasoning.length === 0) return '';

  const sample = withReasoning.slice(0, 60)
    .map(b => `${b.name}: ${b.reason}`)
    .join('\n');

  const prompt = `Here are brands a curated shopping app's brand judge has rejected, with the reasoning given at the time:

${sample}

Summarize the recurring PATTERNS in why brands get rejected — the underlying
traits to avoid, not a list of brand names (e.g. "mass-market pricing without
a craft story", "generic template site with stock photography", "scaled into
wide wholesale and lost design specificity"). 3-6 short phrases, no brand names.

Respond with ONLY a JSON array of strings, no other text.`;

  try {
    const res = await fetchWithTimeout('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': anthropicKey, 'anthropic-version': '2023-06-01' },
      body: JSON.stringify({ model: 'claude-haiku-4-5-20251001', max_tokens: 400, messages: [{ role: 'user', content: prompt }] }),
    });
    if (!res.ok) return '';
    const data = await res.json();
    const text = data.content?.[0]?.text ?? '[]';
    const match = text.match(/\[[\s\S]*\]/);
    const patterns: string[] = match ? JSON.parse(match[0]) : [];
    return patterns.join('; ');
  } catch {
    return '';
  }
}

// ─── LAYER 0: HAND-PICKED BRAND SEEDS ───────────────────────────────────────
// For each brand Sam has explicitly hand-picked, run a dedicated single-brand
// Exa search. These are the strongest possible taste signal — not random
// clusters of approved brands, but the specific labels Sam has curated.
// Runs one search per brand in parallel (no cluster budget to worry about).

async function discoverFromHandPicked(
  exaKey: string,
  handPickedBrands: { name: string; domain: string }[],
  rejectedNames: string[],
  rejectionPatterns: string,
  knownDomains: Set<string>,
): Promise<Candidate[]> {
  if (handPickedBrands.length === 0) return [];
  const results = await Promise.allSettled(
    handPickedBrands.map(brand =>
      searchExaStorefronts(
        exaKey,
        `independent brand with the same aesthetic, craft quality, and downtown point of view as ${brand.name} — same vibe, DTC, founder-led, not mall-owned or mass-distributed`,
        rejectedNames,
        rejectionPatterns,
      ).then(found =>
        found
          .filter(b => !knownDomains.has(b.domain))
          .map(b => ({ ...b, source: 'hand_picked' as const })),
      ),
    ),
  );
  const candidates: Candidate[] = [];
  for (const result of results) {
    if (result.status === 'fulfilled') candidates.push(...result.value);
  }
  return candidates;
}

// ─── LAYER 1: SEED-BASED ────────────────────────────────────────────────────

async function discoverFromSeeds(
  exaKey: string,
  approved: { name: string; domain: string }[],
  rejectedNames: string[],
  rejectionPatterns: string,
  tasteProfile: string,
  knownDomains: Set<string>,
): Promise<Candidate[]> {
  if (approved.length === 0) return [];

  // Shuffle so different clusters surface each weekly run
  const shuffled = [...approved].sort(() => Math.random() - 0.5);

  // Build clusters of 4–5 brands each, cap at 4 clusters to stay in budget
  const CLUSTER_SIZE = 4;
  const clusters: typeof approved[] = [];
  for (let i = 0; i < Math.min(shuffled.length, CLUSTER_SIZE * 4); i += CLUSTER_SIZE) {
    clusters.push(shuffled.slice(i, i + CLUSTER_SIZE));
  }

  const profileClause = tasteProfile ? ` ${tasteProfile}` : '';
  const candidates: Candidate[] = [];
  for (const cluster of clusters) {
    const seedNames = cluster.map(b => b.name).join(', ');
    try {
      const found = await searchExaStorefronts(
        exaKey,
        `independent brand with the same cool, considered, craft-driven downtown aesthetic and customer as ${seedNames} — small team or founder story, strong visual identity, direct-to-consumer, not mall-owned or mass-distributed.${profileClause}`,
        rejectedNames,
        rejectionPatterns,
      );
      for (const b of found) {
        if (!knownDomains.has(b.domain)) candidates.push({ ...b, source: 'seed' });
      }
    } catch { /* skip failed cluster, continue */ }
  }
  return candidates;
}


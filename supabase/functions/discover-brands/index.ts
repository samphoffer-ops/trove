// ─── SHARED: EXA STOREFRONT SEARCH ──────────────────────────────────────────

async function searchExaStorefronts(
  apiKey: string,
  query: string,
  rejectedNames: string[],
  rejectionPatterns: string = '',
): Promise<{ name: string; domain: string }[]> {
  const antiExamples = [
    rejectedNames.length > 0
      ? ` Avoid recommending brands similar to these already-rejected examples: ${rejectedNames.slice(0, 12).join(', ')}.`
      : '',
    rejectionPatterns
      ? ` Also avoid brands with these traits that have gotten brands rejected before: ${rejectionPatterns}.`
      : '',
  ].join('');

  const res = await fetchWithTimeout('https://api.exa.ai/search', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-api-key': apiKey },
    body: JSON.stringify({
      query: `${query} official online store`,
      type: 'auto',
      numResults: 8,
      systemPrompt: `Return only actual brand storefronts (the brand's own site where they sell directly) — never marketplaces, department stores, multi-brand retailers, listicle articles, or social media profiles. The brand must be an independent DTC label with a clear identity and quality positioning.${antiExamples} Extract the brand's real display name and bare domain (no https://, no www, no path).`,
      outputSchema: {
        type: 'object',
        required: ['brands'],
        properties: {
          brands: {
            type: 'array',
            items: {
              type: 'object',
              required: ['name', 'domain'],
              properties: {
                name: { type: 'string', description: 'Brand display name' },
                domain: { type: 'string', description: 'Bare domain, e.g. example.com' },
              },
            },
          },
        },
      },
    }),
  });
  if (!res.ok) return [];
  const data = await res.json();
  return (data.output?.content?.brands ?? [])
    .map((b: { name?: string; domain?: string }) => ({
      name: b.name ?? '',
      domain: cleanDomain(b.domain ?? ''),
    }))
    .filter((b: { name: string; domain: string }) => b.name && b.domain);
}

// Resolves a known brand NAME to its real domain via Exa's own search +
// extraction, rather than trusting an LLM's guessed "brandname.com". The
// editorial and Nuuly layers used to ask Claude to predict a domain directly
// from a brand name mentioned in text — measured 0% of those guesses ever
// resolved to a real scrapeable storefront (42 candidates, 0 reached the
// judge), against 24–39% for layers that use Exa to find the real page.
// This function gives editorial/Nuuly the same real-search treatment.
async function resolveDomainForBrand(exaKey: string, brandName: string): Promise<string | null> {
  try {
    const res = await fetchWithTimeout('https://api.exa.ai/search', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': exaKey },
      body: JSON.stringify({
        query: `${brandName} official online store`,
        type: 'auto',
        numResults: 3,
        systemPrompt: 'Return only the brand\'s own official storefront (where they sell directly) — never marketplaces, department stores, multi-brand retailers, listicle articles, or social media profiles. Extract the bare domain (no https://, no www, no path).',
        outputSchema: {
          type: 'object',
          required: ['brands'],
          properties: {
            brands: {
              type: 'array',
              items: { type: 'object', required: ['domain'], properties: { domain: { type: 'string' } } },
            },
          },
        },
      }),
    });
    if (!res.ok) return null;
    const data = await res.json();
    const domain = data.output?.content?.brands?.[0]?.domain;
    return domain ? cleanDomain(domain) : null;
  } catch {
    return null;
  }
}

// ─── LAYER 4: NUULY ─────────────────────────────────────────────────────────
//
// Nuuly (nuuly.com) carries hundreds of independent brands alongside the URBN
// family labels — it's one of the strongest external curation signals we have.
// We crawl their brands listing via Exa, extract brand slugs from URLs + page
// text, then use Claude to resolve each to a display name + likely DTC domain,
// filtering out Anthropologie/Free People/UO private labels in the same step.

async function discoverFromNuuly(
  exaKey: string,
  anthropicKey: string,
  knownDomains: Set<string>,
  rejectedNames: string[],
  rejectionPatterns: string,
): Promise<Candidate[]> {
  try {
    const res = await fetchWithTimeout('https://api.exa.ai/search', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': exaKey },
      body: JSON.stringify({
        query: 'fashion brands available to rent clothing',
        type: 'keyword',
        numResults: 25,
        includeDomains: ['nuuly.com'],
        contents: { text: { maxCharacters: 4000 } },
      }),
    });
    if (!res.ok) return [];
    const data = await res.json();
    const results: { url?: string; text?: string }[] = data.results ?? [];

    // Pull brand slugs from URLs like /rent/brands/{slug}
    const brandSlugs = new Set<string>();
    for (const r of results) {
      const match = r.url?.match(/\/rent\/brands\/([^/?#]+)/);
      if (match) brandSlugs.add(match[1].replace(/-/g, ' '));
    }

    const combinedText = results.map(r => r.text ?? '').join('\n').slice(0, 5000);
    if (!combinedText.trim() && brandSlugs.size === 0) return [];

    const antiExamples = [
      rejectedNames.length > 0
        ? `Do NOT include brands similar to these already-rejected examples: ${rejectedNames.slice(0, 10).join(', ')}.`
        : '',
      rejectionPatterns
        ? `Also avoid brands with these traits that have gotten brands rejected before: ${rejectionPatterns}.`
        : '',
    ].filter(Boolean).join(' ');
    const antiExamplesBlock = antiExamples ? `\n\n${antiExamples}` : '';

    const extractRes = await fetchWithTimeout('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': anthropicKey, 'anthropic-version': '2023-06-01' },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 1200,
        messages: [{
          role: 'user',
          content: `You are identifying independent fashion brands from Nuuly's rental catalog.

Brand slugs extracted from nuuly.com URLs: ${[...brandSlugs].join(', ') || 'see page text'}

Page text:
${combinedText}${antiExamplesBlock}

Provide each brand's display name.

SKIP these — they are URBN private labels or sub-brands, not independent:
Anthropologie, Free People, Urban Outfitters, BHLDN, Maeve, Pilcro, Cloth & Stone,
Sanctuary, Floreat, Holding Horses, Eliza J, Moon River, BB Dakota.
Also skip any brand that is obviously mass-market, fast fashion, or not DTC.

Respond ONLY with a JSON array of brand names — no other text:
["Brand Name", ...]`,
        }],
      }),
    });

    if (!extractRes.ok) return [];
    const extractData = await extractRes.json();
    const text = extractData.content?.[0]?.text ?? '[]';
    const match = text.match(/\[[\s\S]*\]/);
    if (!match) return [];

    const names: string[] = JSON.parse(match[0]).slice(0, 15);
    const candidates: Candidate[] = [];
    for (const name of names) {
      if (!name) continue;
      await sleep(300);
      const domain = await resolveDomainForBrand(exaKey, name);
      if (domain && !knownDomains.has(domain)) {
        candidates.push({ name, domain, source: 'nuuly' });
      }
    }
    return candidates;
  } catch {
    return [];
  }
}

